
import json
import os

import streamlit as st
from openai import OpenAI

st.set_page_config(
    page_title="AI Quiz Generator",
    page_icon="🧠",
    layout="centered",
)

st.title("🧠 AI Quiz Generator")
st.write("Create a quiz on any topic and test your knowledge!")

# Read the API key securely from Streamlit Secrets
# or from an environment variable.
try:
    api_key = st.secrets.get("OPENAI_API_KEY", "")
except Exception:
    api_key = ""

api_key = api_key or os.getenv("OPENAI_API_KEY", "")

with st.sidebar:
    st.header("Quiz Settings")
    topic = st.text_input(
        "Enter a topic",
        placeholder="e.g. Python, Biology, AI",
    )
    difficulty = st.selectbox(
        "Difficulty",
        ["Easy", "Medium", "Hard"],
    )
    num_questions = st.slider(
        "Number of questions",
        min_value=3,
        max_value=10,
        value=5,
    )
    st.caption("Questions are generated by an AI model.")

if "quiz" not in st.session_state:
    st.session_state.quiz = None
if "submitted" not in st.session_state:
    st.session_state.submitted = False

if st.button("✨ Generate Quiz", type="primary", use_container_width=True):
    if not topic.strip():
        st.warning("Please enter a topic first.")
    elif not api_key:
        st.error(
            "API key not found. Add OPENAI_API_KEY "
            "in your Streamlit app Secrets."
        )
    else:
        prompt = f"""
Create {num_questions} multiple-choice quiz questions
about: {topic.strip()}
Difficulty: {difficulty}

Return ONLY a valid JSON object in this exact format:
{{
  "questions": [
    {{
      "question": "Question text",
      "options": [
        "Option A", "Option B", "Option C", "Option D"
      ],
      "answer": 0,
      "explanation": "Short explanation"
    }}
  ]
}}

Rules:
- Each question must have exactly four options.
- The answer must be an integer from 0 to 3.
- The answer is the zero-based index of the correct option.
- Ensure one correct answer per question.
- Make questions clear, educational, and factually accurate.
- Include a short explanation for each answer.
- Generate exactly {num_questions} questions.
"""

        try:
            client = OpenAI(api_key=api_key)

            with st.spinner("AI is creating your quiz..."):
                response = client.responses.create(
                    model="gpt-5.5",
                    input=prompt,
                    text={"format": {"type": "json_object"}},
                )

            data = json.loads(response.output_text)
            questions = data.get("questions", [])

            # Validate the model output before showing it.
            if len(questions) != num_questions:
                raise ValueError(
                    "The AI returned an unexpected number of questions. "
                    "Please try again."
                )

            for q in questions:
                if (
                    not isinstance(q.get("question"), str)
                    or not isinstance(q.get("options"), list)
                    or len(q["options"]) != 4
                    or not all(
                        isinstance(option, str) and option.strip()
                        for option in q["options"]
                    )
                    or type(q.get("answer")) is not int
                    or q["answer"] not in range(4)
                    or not isinstance(q.get("explanation"), str)
                ):
                    raise ValueError(
                        "The AI returned an invalid question. Please retry."
                    )

            st.session_state.quiz = questions
            st.session_state.submitted = False
            st.rerun()

        except Exception as e:
            st.error(f"Could not generate the quiz: {e}")

questions = st.session_state.quiz

if questions:
    st.divider()
    st.subheader(f"Your {difficulty} Quiz: {topic}")
    st.caption(f"{len(questions)} questions • 1 point each")

    # The form keeps all selected answers until submission.
    with st.form("quiz_form"):
        selected_answers = []

        for i, q in enumerate(questions):
            st.markdown(f"**Q{i + 1}. {q['question']}**")

            choice = st.radio(
                "Choose one answer:",
                options=range(4),
                format_func=lambda idx, opts=q["options"]: opts[idx],
                key=f"answer_{i}",
                index=None,
                label_visibility="collapsed",
            )
            selected_answers.append(choice)
            st.write("")

        submitted = st.form_submit_button(
            "Submit Answers",
            type="primary",
            use_container_width=True,
        )

    if submitted:
        st.session_state.submitted = True
        st.session_state.score = sum(
            selected == q["answer"]
            for selected, q in zip(selected_answers, questions)
        )
        st.session_state.final_answers = selected_answers

    if st.session_state.submitted:
        score = st.session_state.score
        total = len(questions)

        st.divider()
        st.header("📊 Your Results")
        st.metric("Your Score", f"{score} / {total}")
        st.progress(score / total)

        if score == total:
            st.success("Excellent! You got every question right!")
        elif score >= total / 2:
            st.info("Good work! Review any incorrect answers below.")
        else:
            st.warning("Keep practising. Review the explanations below.")

        for i, (q, selected) in enumerate(
            zip(questions, st.session_state.final_answers)
        ):
            correct = selected == q["answer"]

            with st.expander(
                f"Q{i + 1}: {'✅ Correct' if correct else '❌ Incorrect'}"
            ):
                st.write(q["question"])

                if selected is None:
                    st.write("Your answer: Not answered")
                else:
                    st.write(
                        "Your answer: " + q["options"][selected]
                    )

                st.write(
                    "Correct answer: " + q["options"][q["answer"]]
                )
                st.write("Explanation: " + q["explanation"])

        if st.button("🔄 Create Another Quiz"):
            st.session_state.quiz = None
            st.session_state.submitted = False
            st.rerun()
